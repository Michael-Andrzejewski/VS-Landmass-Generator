"""Write src/ClutterSupport.cs: which block faces each clutter model touches.

Read from clutter-catalog-raw.json (the model's bounds at rotation 0). A face
counts as touched when the model comes within TOL of it (one texture pixel is
0.0625). The clutter commit uses this to check that a prop really rests on,
hangs from or is fixed to something, and to turn a wall prop to its wall.

Bits: 1 west (-x), 2 east (+x), 4 down (-y), 8 up (+y), 16 north (-z), 32 south (+z).

    python -I gen_clutter_support.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
TOL = 0.07


def mask(bmin, bmax):
    m = 0
    if bmin[0] <= TOL: m |= 1
    if bmax[0] >= 1 - TOL: m |= 2
    if bmin[1] <= TOL: m |= 4
    if bmax[1] >= 1 - TOL: m |= 8
    if bmin[2] <= TOL: m |= 16
    if bmax[2] >= 1 - TOL: m |= 32
    return m


def main():
    rows = json.load(open(os.path.join(HERE, "clutter-catalog-raw.json"), encoding="utf-8"))["rows"]
    out = {}
    for r in rows:
        if r.get("_bmin") is None:
            continue
        key = (r["block"] + "|" + r["type"]).lower()
        out[key] = (mask(r["_bmin"], r["_bmax"]), r["_bmin"], r["_bmax"])
    lines = ["// Generated by tools/clutter-catalog/gen_clutter_support.py from the clutter catalog. Do not edit by hand.",
             "using System.Collections.Generic;", "", "namespace LandmassGenerator;", "",
             "internal static class ClutterSupport", "{",
             "    // block|type -> the faces the model touches at rotation 0 (1 west, 2 east, 4 down, 8 up, 16 north, 32 south)",
             "    // and its bounds in the block (x1, y1, z1, x2, y2, z2)",
             "    internal static readonly Dictionary<string, (byte Touch, float X1, float Y1, float Z1, float X2, float Y2, float Z2)> Types = new()", "    {"]
    f = lambda v: ("%.3f" % v).rstrip("0").rstrip(".") + "f"
    for k in sorted(out):
        m, a, b = out[k]
        lines.append('        ["%s"] = (%d, %s, %s, %s, %s, %s, %s),' % (k.replace("\\", "\\\\").replace('"', '\\"'), m, f(a[0]), f(a[1]), f(a[2]), f(b[0]), f(b[1]), f(b[2])))
    lines += ["    };", "}", ""]
    path = os.path.join(REPO, "src", "ClutterSupport.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", path, len(out), "types")
    for k in sorted(out):
        t = k.split("|", 1)[1]
        if any(t.startswith(p) for p in ("gauge", "valve", "switch", "lever", "sightglass", "wallhook", "lightsource/on/gas-wall", "lightsource/on/lumi")):
            m = out[k][0]
            print("  %-48s %s" % (k, ",".join(n for b, n in ((1, "W"), (2, "E"), (4, "D"), (8, "U"), (16, "N"), (32, "S")) if m & b) or "none"))


if __name__ == "__main__":
    main()
